#!/usr/bin/env python3
"""Generate fixtures/sample_data.json: a DEMO dataset, not the official data.

Every case is deterministic. The dataset deliberately contains one failure of
each report category so the failure analysis has something real to analyse.
"""

import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from main import make_cross, make_x  # noqa: E402


def noisy(matrix, seed, amount=0.08):
    rng = random.Random(seed)
    return [
        [round(min(1.0, max(0.0, v + rng.uniform(-amount, amount))), 3) for v in row]
        for row in matrix
    ]


def near_tie(n, cross_only, x_only):
    """Zeros, except cells that only the Cross filter or only the X filter see.

    Cross-only cells sit on the top of the middle column, X-only cells walk down
    the main diagonal, so each MAC accumulates its list in the order given.
    """
    grid = [[0.0] * n for _ in range(n)]
    for row, value in enumerate(cross_only):
        grid[row][n // 2] = value
    for row, value in enumerate(x_only):
        grid[row][row] = value
    return grid


def build():
    filters = {
        "size_{}".format(n): {"cross": make_cross(n), "x": make_x(n)}
        for n in (5, 13, 25)
    }
    patterns = {
        # Clean cases, using every accepted spelling of the labels.
        "size_5_1": {"input": make_x(5), "expected": "x"},
        "size_5_2": {"input": make_cross(5), "expected": "+"},
        "size_5_3": {"input": noisy(make_cross(5), seed=53), "expected": "+"},
        "size_13_1": {"input": make_cross(13), "expected": " CROSS "},
        "size_13_2": {"input": noisy(make_x(13), seed=132), "expected": "X"},
        "size_25_1": {"input": make_cross(25), "expected": "+"},
        "size_25_2": {"input": make_x(25), "expected": "x"},
        # 0.1 + 0.2 + 0.6 and 0.3 + 0.3 + 0.3 differ only by rounding: a tie.
        "size_13_3": {"input": near_tie(13, [0.1, 0.2, 0.6], [0.3, 0.3, 0.3]), "expected": "x"},
        # A real gap of 2e-9 sits outside epsilon, so this one is decided.
        "size_25_3": {"input": near_tie(25, [0.5 + 2e-9], [0.5]), "expected": "+"},
        # One deliberate failure per category.
        "size_5_4": {"input": make_cross(4), "expected": "+"},
        "size_5_5": {"input": make_cross(5), "expected": "o"},
        "size_5_6": {"input": make_x(5), "expected": "+"},
        "size_13_4": {"expected": "+"},
        "size_25_4": {"input": [["1"] * 25] * 25, "expected": "x"},
        "size_7_1": {"input": make_cross(7), "expected": "+"},
        "pattern_1": {"input": make_cross(5), "expected": "+"},
    }
    return {
        "_notice": "Demo fixture generated by tools/make_fixture.py. Not the official assignment data.",
        "filters": filters,
        "patterns": patterns,
    }


def main():
    path = os.path.join(ROOT, "fixtures", "sample_data.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(build(), handle, ensure_ascii=False, indent=1)
        handle.write("\n")
    print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
